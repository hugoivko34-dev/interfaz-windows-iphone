"""USB HID boot keyboard mapping by set-1 scan code."""

# (scan code, extended) -> HID keyboard usage.
SCAN_TO_HID = {}
for _scan, _usage in zip(
    (0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24,
     0x25, 0x26, 0x32, 0x31, 0x18, 0x19, 0x10, 0x13, 0x1F, 0x14,
     0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C), range(0x04, 0x1E)):
    SCAN_TO_HID[(_scan, False)] = _usage
for _scan, _usage in zip((0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B), range(0x1E, 0x28)):
    SCAN_TO_HID[(_scan, False)] = _usage
SCAN_TO_HID.update({
    (0x01, False): 0x29, (0x0E, False): 0x2A, (0x0F, False): 0x2B,
    (0x39, False): 0x2C, (0x1C, False): 0x28, (0x01, True): 0x4C,
    (0x0E, True): 0x4C, (0x0C, False): 0x2D, (0x0D, False): 0x2E,
    (0x1A, False): 0x2F, (0x1B, False): 0x30, (0x2B, False): 0x31,
    (0x27, False): 0x33, (0x28, False): 0x34, (0x29, False): 0x35,
    (0x33, False): 0x36, (0x34, False): 0x37, (0x35, False): 0x38,
    (0x56, False): 0x64, (0x3A, False): 0x39,
    (0x3B, False): 0x3A, (0x3C, False): 0x3B, (0x3D, False): 0x3C,
    (0x3E, False): 0x3D, (0x3F, False): 0x3E, (0x40, False): 0x3F,
    (0x41, False): 0x40, (0x42, False): 0x41, (0x43, False): 0x42,
    (0x44, False): 0x43, (0x57, False): 0x44, (0x58, False): 0x45,
    (0x48, True): 0x52, (0x50, True): 0x51, (0x4D, True): 0x4F,
    (0x4B, True): 0x50, (0x47, True): 0x4A, (0x4F, True): 0x4D,
    (0x49, True): 0x4B, (0x51, True): 0x4E, (0x52, True): 0x49,
    (0x53, True): 0x4C, (0x1C, True): 0x58, (0x5D, True): 0x65,
})

# VK -> HID modifier bit (LCtrl, LShift, LAlt, LGUI, RCtrl, RShift, RAlt, RGUI).
# The Windows key is GUI, i.e. Cmd on iOS.
MODIFIER_VK = {
    0xA2: 0x01, 0xA0: 0x02, 0xA4: 0x04, 0x5B: 0x08,
    0xA3: 0x10, 0xA1: 0x20, 0xA5: 0x40, 0x5C: 0x80,
}

CONSUMER_VK = {0xAF: 0x00E9, 0xAE: 0x00EA, 0xAD: 0x00E2, 0xB3: 0x00CD}
